#!/usr/bin/env python3
"""
Turns the dashboard's static files (esp32_firmware/web/*) into gzip-compressed arrays the box serves straight
from flash. One set per product (see esp32_firmware/web/README.md, "One set of files per product"):

  include/WebAssetsPhones.h  the box with rental phones (the full box and the PisoPhone-only box)
  include/WebAssetsBase.h    the PisoWiFi-only box: nothing of the phones' part
  include/WebAssets.h        picks one of the two by PISO_HAS_PHONES (include/Product.h)

  python3 scripts/embed_web.py            regenerate the headers (do this after editing anything in web/)
  python3 scripts/embed_web.py --check    exit 1 if a header is out of date (CI runs this)

The output is reproducible (fixed gzip timestamp), so the check is exact. Each asset gets a version tag taken
from its content hash; the pages link to /assets/<name>?v=<tag>, so browsers cache an asset until it changes.
"""

import gzip
import hashlib
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "esp32_firmware")
WEB_DIR = os.path.join(ROOT, "web")
INCLUDE = os.path.join(ROOT, "include")
OUT = os.path.join(INCLUDE, "WebAssets.h")

# file in web/ -> (URL name, content type, C identifier)
ASSETS = [
    ("portal.css", "text/css; charset=utf-8", "PORTAL_CSS"),
    ("portal-core.js", "application/javascript; charset=utf-8", "PORTAL_CORE_JS"),
    ("portal-modals.js", "application/javascript; charset=utf-8", "PORTAL_MODALS_JS"),
    ("superadmin.js", "application/javascript; charset=utf-8", "SUPERADMIN_JS"),
    ("jsqr.js", "application/javascript; charset=utf-8", "JSQR_JS"),
    ("adminqr.js", "application/javascript; charset=utf-8", "ADMINQR_JS"),
    ("ota.js", "application/javascript; charset=utf-8", "OTA_JS"),
    ("brand.png", "image/png", "BRAND_PNG"),
    ("mascot.png", "image/png", "MASCOT_PNG"),
]


def _read(name):
    with open(os.path.join(WEB_DIR, name), "rb") as f:
        return f.read()


def _strip_js_comments(text):
    """Drops the lines that are only a // comment (so a word in a comment does not reach the box)."""
    return "\n".join(line for line in text.split("\n") if not line.lstrip().startswith("//"))


def _css(text, has_phones):
    """portal.css: the rules between /*@phones*/ and /*@end*/ stay only for the products with phones; comments are dropped."""
    text = re.sub(r"/\*@phones\*/\n(.*?)/\*@end\*/\n?", (lambda m: m.group(1)) if has_phones else "", text, flags=re.S)
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def assets_for(has_phones):
    """The files the box serves in one product, as (URL name, content type, C identifier, bytes)."""
    out = []
    for name, ctype, ident in ASSETS:
        raw = _read(name)
        if name in ("portal-core.js", "portal-modals.js"):
            text = raw.decode("utf-8")
            if has_phones:
                text += "\n" + _read(name.replace(".js", "-phones.js")).decode("utf-8")
            if name == "portal-core.js":
                text += "\n" + _read("portal-core-end.js").decode("utf-8")
            raw = _strip_js_comments(text).encode("utf-8")
        elif name.endswith(".js") and name != "jsqr.js":   # (jsqr.js is the vendored reader: left as it is)
            raw = _strip_js_comments(raw.decode("utf-8")).encode("utf-8")
        elif name == "portal.css":
            raw = _css(raw.decode("utf-8"), has_phones).encode("utf-8")
        out.append((name, ctype, ident, raw))
    return out


def render(has_phones):
    guard = "WEB_ASSETS_PHONES_H" if has_phones else "WEB_ASSETS_BASE_H"
    out = [
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "// GENERATED by scripts/embed_web.py from esp32_firmware/web/. Do not edit; edit web/ and regenerate.",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    table = []
    for name, ctype, ident, raw in assets_for(has_phones):
        gz = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
        # Python 3.13 writes 255 ("unknown") in the header's OS byte where 3.11 and 3.12 write 3 ("Unix"); the
        # compressed data is the same. Pin it so the header is byte-for-byte the same on every Python version.
        gz[9] = 3
        gz = bytes(gz)
        tag = hashlib.sha256(raw).hexdigest()[:12]
        body = ",".join(str(b) for b in gz)
        out.append(f"// {name}: {len(raw)} bytes, {len(gz)} gzipped")
        out.append(f"static const uint8_t {ident}_GZ[] = {{{body}}};")
        out.append(f'static const char {ident}_V[] = "{tag}";')
        out.append("")
        table.append((name, ctype, ident))
    out.append("struct WebAsset {")
    out.append("    const char* name;")
    out.append("    const char* contentType;")
    out.append("    const uint8_t* gz;")
    out.append("    size_t gzLen;")
    out.append("    const char* version;")
    out.append("};")
    out.append("")
    out.append("static const WebAsset WEB_ASSETS[] = {")
    for name, ctype, ident in table:
        out.append(f'    {{"{name}", "{ctype}", {ident}_GZ, sizeof({ident}_GZ), {ident}_V}},')
    out.append("};")
    out.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);")
    out.append("")
    out.append(f"#endif // {guard}")
    return "\n".join(out) + "\n"


WRAPPER = """#ifndef WEB_ASSETS_H
#define WEB_ASSETS_H

// GENERATED by scripts/embed_web.py. Do not edit. The served dashboard files of this image: the box with phones (the full product
// and the PisoPhone-only one) or the one without (PisoWiFi only), chosen by include/Product.h.
#include "Product.h"

#if PISO_HAS_PHONES
#include "WebAssetsPhones.h"
#else
#include "WebAssetsBase.h"
#endif

#endif // WEB_ASSETS_H
"""


def outputs():
    return {
        OUT: WRAPPER,
        os.path.join(INCLUDE, "WebAssetsPhones.h"): render(True),
        os.path.join(INCLUDE, "WebAssetsBase.h"): render(False),
    }


def main():
    files = outputs()
    if "--check" in sys.argv:
        stale = [os.path.basename(p) for p, text in files.items()
                 if (open(p, encoding="utf-8").read() if os.path.exists(p) else "") != text]
        if stale:
            print(f"{', '.join(stale)} out of date: run python3 scripts/embed_web.py and commit the result.")
            sys.exit(1)
        print("WebAssets.h is up to date.")
        return
    for path, text in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
