#!/usr/bin/env python3
"""Makes the owner's admin QR code: the one code that logs you in as super admin on every coin box.

    python3 scripts/make_admin_qr.py                       uses ~/pisophone-superadmin.key (made on the first run)
    python3 scripts/make_admin_qr.py --private my.key --out admin-qr.png

The QR code holds a private key. On a box's login page, tap "Scan admin QR" and photograph the code: your phone's browser signs
a one-time challenge from the box with the key and sends only the signature, so the key never leaves your phone. The boxes
carry the matching PUBLIC key in their firmware (esp32_firmware/include/SuperAdminPubKey.h). There is no password to set, publish
or rotate.

  - The first run makes the key (and writes the public key header: commit it, then update the boxes once, Update > Install update).
  - Every run after that draws the same QR code again from the same key file, so you can reprint it any time.
  - To change the key (the QR code leaked or was lost): run with --new, commit the new header, update every box.

Keep the key file and the picture private: whoever has either is super admin on your boxes. Needs:
    pip install cryptography qrcode pillow
"""
import argparse
import base64
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PUBKEY_HEADER = os.path.join(HERE, "..", "esp32_firmware", "include", "SuperAdminPubKey.h")
DEFAULT_KEY = os.path.join(os.path.expanduser("~"), "pisophone-superadmin.key")
PREFIX = "PISOADMIN1"


def _crypto():
    try:
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import ec, utils
    except ImportError:
        sys.exit("This tool needs: pip install cryptography qrcode pillow")
    return hashes, serialization, ec, utils


def b64u(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode().rstrip("=")


def unb64u(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def payload_for(key) -> str:
    """The text in the QR code: PISOADMIN1.<d>.<x>.<y> (the P-256 private number and the public point, 32 bytes each, base64url)."""
    numbers = key.private_numbers()
    return ".".join([PREFIX, b64u(numbers.private_value.to_bytes(32, "big")),
                     b64u(numbers.public_numbers.x.to_bytes(32, "big")), b64u(numbers.public_numbers.y.to_bytes(32, "big"))])


def key_from_payload(text: str):
    """The private key in a QR payload (a ValueError when it is not a valid one)."""
    _, _, ec, _ = _crypto()
    parts = text.strip().split(".")
    if len(parts) != 4 or parts[0] != PREFIX:
        raise ValueError("not a PisoPhone admin code")
    d, x, y = (int.from_bytes(unb64u(p), "big") for p in parts[1:])
    key = ec.derive_private_key(d, ec.SECP256R1())
    pub = key.public_key().public_numbers()
    if (pub.x, pub.y) != (x, y):
        raise ValueError("the code is damaged (its public part does not match)")
    return key


def signed_message(nonce: str, box_id: str) -> str:
    """Must match adminqr::signedMessage() in esp32_firmware/include/AdminQrAuth.h and the page's script (web/adminqr.js)."""
    return f"pisophone-admin-v1|{nonce}|{box_id}"


def sign(key, nonce: str, box_id: str) -> str:
    """The signature (DER, base64) the page sends for a challenge: for tests; the real signing happens in the browser."""
    hashes, _, ec, _ = _crypto()
    return base64.b64encode(key.sign(signed_message(nonce, box_id).encode(), ec.ECDSA(hashes.SHA256()))).decode()


def write_pubkey_header(public_key, path=PUBKEY_HEADER):
    _, serialization, _, _ = _crypto()
    der = public_key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    body = ", ".join(f"0x{b:02x}" for b in der)
    with open(path, "w") as f:
        f.write("#ifndef SUPER_ADMIN_PUB_KEY_H\n#define SUPER_ADMIN_PUB_KEY_H\n\n"
                "// Generated by scripts/make_admin_qr.py. Public key only.\n"
                "// DER SubjectPublicKeyInfo of the ECDSA P-256 key whose private half is in the owner's admin QR code.\n"
                "#include <stddef.h>\n#include <stdint.h>\n\n"
                "// clang-format off\n"
                f"static const uint8_t SUPER_ADMIN_PUBKEY_DER[] = {{{body}}};\n"
                "// clang-format on\n"
                "static const size_t SUPER_ADMIN_PUBKEY_LEN = sizeof(SUPER_ADMIN_PUBKEY_DER);\n\n"
                "#endif\n")


def header_matches(public_key, path=PUBKEY_HEADER) -> bool:
    """True when the firmware's public key header holds this key's public half."""
    _, serialization, _, _ = _crypto()
    der = public_key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    try:
        with open(path) as f:
            return ", ".join(f"0x{b:02x}" for b in der) in f.read()
    except OSError:
        return False


def draw_card(text: str, path: str):
    """A printable picture: the QR code with a title, drawn with whole pixels per module so a phone camera reads it easily."""
    try:
        import qrcode
        from qrcode.constants import ERROR_CORRECT_M
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        sys.exit("This tool needs: pip install cryptography qrcode pillow")
    qr = qrcode.QRCode(error_correction=ERROR_CORRECT_M, box_size=1, border=4)
    qr.add_data(text)
    qr.make(fit=True)
    modules = qr.modules_count + 2 * qr.border
    qr.box_size = max(1, 760 // modules)
    code = qr.make_image(fill_color="black", back_color="white").convert("RGB")
    width = max(code.width + 80, 900)
    card = Image.new("RGB", (width, code.height + 260), "white")
    draw = ImageDraw.Draw(card)
    try:
        font = ImageFont.truetype("DejaVuSans-Bold.ttf", 44)
        small = ImageFont.truetype("DejaVuSans.ttf", 30)
    except OSError:
        font = small = ImageFont.load_default()
    draw.text((width // 2, 70), "PisoPhone owner admin key", fill="black", font=font, anchor="mm")
    draw.text((width // 2, 130), "Keep private: opens super admin on every box", fill=(90, 90, 90), font=small, anchor="mm")
    card.paste(code, ((width - code.width) // 2, 170))
    draw.text((width // 2, code.height + 215), "Box login page > Scan admin QR", fill=(90, 90, 90), font=small, anchor="mm")
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        card.save(f, "PNG")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--private", default=DEFAULT_KEY, help=f"the key file (made when it does not exist; default {DEFAULT_KEY})")
    p.add_argument("--out", default="pisophone-admin-qr.png", help="the picture to write (default pisophone-admin-qr.png)")
    p.add_argument("--new", action="store_true", help="replace the key with a new one (the old QR code stops working once the boxes are updated)")
    args = p.parse_args()
    _, serialization, ec, _ = _crypto()

    made = False
    if args.new or not os.path.exists(args.private):
        if os.path.exists(args.private):
            os.replace(args.private, args.private + ".old")
            print(f"The old key was kept as {args.private}.old")
        key = ec.generate_private_key(ec.SECP256R1())
        pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
        fd = os.open(args.private, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "wb") as f:
            f.write(pem)
        made = True
    else:
        with open(args.private, "rb") as f:
            key = serialization.load_pem_private_key(f.read(), password=None)
    if made:
        write_pubkey_header(key.public_key())
        print(f"New key written to {args.private} (back it up somewhere safe; it is the only copy).")
        print(f"Its public half is in {os.path.relpath(PUBKEY_HEADER)}: commit it, then update every box once")
        print("(a box only trusts the key it was built with).")
    elif not header_matches(key.public_key()):
        print(f"WARNING: {os.path.relpath(PUBKEY_HEADER)} holds a different public key than {args.private}: boxes built from it")
        print("will not accept this QR code. Run with --new to make a matching pair, or restore the right header.")
    draw_card(payload_for(key), args.out)
    print(f"Admin QR code written to {args.out}. Print it or keep it on your phone; do not share it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
