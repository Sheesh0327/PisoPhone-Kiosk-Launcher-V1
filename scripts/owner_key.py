"""
Shared owner-key helpers for sign_firmware.py, sign_router.py and make_owner_keys.py (needs `pip install cryptography`).

One ECDSA P-256 key signs firmware and router updates. Boxes and routers check those signatures with the public key
built into esp32_firmware/include/LicensePubKey.h (the file name is historical) and tools/pisoportal/owner_key.b64.
Never commit the private key. Keep an offline copy. If it is put in CI at all, it belongs only in the protected GitHub Environment
`production-signing` (main only, reviewer approval; docs/RELEASE.md 2a), never in a plain repository secret.
"""

import base64
import os
import re
import sys

PUBKEY_HEADER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "esp32_firmware", "include",
                             "LicensePubKey.h")
ROUTER_KEY_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools", "pisoportal", "owner_key.b64")


def _crypto():
    try:
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import ec
    except ImportError:
        sys.exit("This tool needs the 'cryptography' package: pip install cryptography")
    return hashes, serialization, ec


def load_private(path: str):
    _, serialization, _ = _crypto()
    with open(path, "rb") as f:
        return serialization.load_pem_private_key(f.read(), password=None)


def repo_public_key(kind: str, path: str = None):
    """The owner public key this repository installs: 'firmware' (the header the boxes are built with) or 'router'
    (tools/pisoportal/owner_key.b64, what routers trust). `path` names another file in the same format. Raises ValueError when
    none is installed or the file cannot be read, so a signing tool fails closed."""
    _, serialization, _ = _crypto()
    path = path or (PUBKEY_HEADER if kind == "firmware" else ROUTER_KEY_FILE)
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError as e:
        raise ValueError(f"cannot read the owner public key {path}: {e}")
    if path.endswith(".h"):
        body = text.split("LICENSE_PUBKEY_DER", 1)[1].split("}", 1)[0] if "LICENSE_PUBKEY_DER" in text else ""
        der = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))
    else:
        try:
            der = base64.b64decode(text.strip())
        except ValueError:
            der = b""
    if not der:
        raise ValueError(f"no owner public key is installed in {path}: run make_owner_keys.py first")
    try:
        return serialization.load_der_public_key(der)
    except ValueError as e:
        raise ValueError(f"the owner public key in {path} is not valid: {e}")


def verify_signature(public_key, sig_b64: str, text: str, what: str = "this release"):
    """Raises ValueError unless `sig_b64` is a valid signature of `text` under `public_key`: the check that a wrong private key
    cannot produce a release nobody can install."""
    hashes, _, ec = _crypto()
    try:
        public_key.verify(base64.b64decode(sig_b64), text.encode(), ec.ECDSA(hashes.SHA256()))
    except Exception:
        raise ValueError(f"the key given does not match the owner public key installed in this repository: the signature of {what} "
                         f"does not verify, so no box or router would accept it. Nothing was written. Use the key made by make_owner_keys.py")


def write_router_key(public_key, path: str = ROUTER_KEY_FILE):
    """The same public key for the router program (tools/pisoportal/owner_key.b64): routers install only updates this key signed."""
    _, serialization, _ = _crypto()
    der = public_key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    with open(path, "w") as f:
        f.write(base64.b64encode(der).decode() + "\n")


def write_pubkey_header(public_key, path: str):
    _, serialization, _ = _crypto()
    der = public_key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    if os.path.realpath(path) == os.path.realpath(PUBKEY_HEADER):
        write_router_key(public_key)   # (not when a test or another header is the target)
    body = ", ".join(f"0x{b:02x}" for b in der)
    with open(path, "w") as f:
        f.write("#ifndef LICENSE_PUB_KEY_H\n#define LICENSE_PUB_KEY_H\n\n"
                "// Generated by scripts/make_owner_keys.py. Public key only.\n"
                "// DER SubjectPublicKeyInfo of the ECDSA P-256 key that signs firmware updates.\n"
                "#include <stddef.h>\n#include <stdint.h>\n\n"
                "// clang-format off\n"
                f"static const uint8_t LICENSE_PUBKEY_DER[] = {{{body}}};\n"
                "// clang-format on\n"
                "static const size_t LICENSE_PUBKEY_LEN = sizeof(LICENSE_PUBKEY_DER);\n\n"
                "#endif\n")
