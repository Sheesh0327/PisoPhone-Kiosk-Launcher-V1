validate_tiers() {
	_req1="$1"; shift
	[ $# -ge 1 ] && [ $# -le 8 ] || return 1
	_seen=" "; _has1=0
	for _t in "$@"; do
		case "$_t" in *:*);; *) return 1 ;; esac
		_p="${_t%%:*}"; _m="${_t#*:}"
		[ "$_p:$_m" = "$_t" ] || return 1
		is_uint "$_p" && is_uint "$_m" || return 1
		[ "$_p" -ge 1 ] && [ "$_p" -le 1000 ] || return 1
		[ "$_m" -ge 1 ] && [ "$_m" -le 10080 ] || return 1
		case "$_seen" in *" $_p "*) return 1 ;; esac
		_seen="$_seen$_p "
		[ "$_p" -eq 1 ] && _has1=1
	done
	[ "$_req1" -eq 1 ] && [ "$_has1" -eq 0 ] && return 1
	return 0
}

